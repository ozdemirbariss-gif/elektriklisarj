def get_language() -> str:
    language = str(st.session_state.get("language", DEFAULT_LANGUAGE)).lower()
    return language if language in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def set_language(language: str) -> None:
    normalized = str(language or "").lower()
    st.session_state["language"] = normalized if normalized in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def t(key: str, **kwargs: Any) -> str:
    language = get_language()
    template = TRANSLATIONS.get(language, {}).get(key) or TRANSLATIONS[DEFAULT_LANGUAGE].get(key) or key
    try:
        return template.format(**kwargs)
    except (KeyError, ValueError):
        return template


def localize_text(value: Any) -> str:
    text = str(value or "").strip()
    if not text or get_language() == DEFAULT_LANGUAGE:
        return text

    key = KNOWN_TEXT_KEYS.get(text)
    if key:
        return t(key)

    source_match = re.fullmatch(r"(\d+) kaynak doğruladı", text)
    if source_match:
        return t("badge.sources", count=source_match.group(1))

    risk_match = re.fullmatch(r"Arıza riski bildirildi \(([^)]+)\)", text)
    if risk_match:
        return t("status.risk", ratio=risk_match.group(1))

    return text
